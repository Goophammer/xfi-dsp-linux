/*
 * ct_winmode.c - "Windows mode" in the kernel: run the X-Fi DSP exactly as Creative's Windows driver sets it up,
 * from a firmware file the USER generates from their own copy of Creative's driver (src/fw_blob.py).
 *
 * Background: replaying Creative's driver start register by register - including loading the DSP program the Windows
 * way, so the DSP kernel builds its own task schedule while modules are linked in - makes the card's own DSP run the
 * Crystalizer etc. under Linux. This file does that replay inside the driver, from the firmware file.
 *
 * Firmware /lib/firmware/ctxfi/xfi20k1-dsp.bin (format in src/fw_blob.py): "XFIW", version, op count, then ops
 *   WRITE reg value | DELAY us | BUFLO reg id | BUFHI reg id    (id = one of ct_dsp_fx.c's transport buffers)
 * Start: echo start > /sys/kernel/xfi_dsp/winmode   (cat it for the state). Sequence:
 *   1. safe-halt all four DSP cores (a previous run may still be running - src/dsp_halt.sh)
 *   2. card interrupts off (GIE) and the driver's own register writes frozen (ct20k1_set_freeze): Linux's mixer
 *      code otherwise re-commits its amixers into Windows' mixer program (seen 2026-10-29)
 *   3. converter address list: SRC 202/203 reload SA/LA from SRCALBA + n*64 at every loop -> our loop, 8 entries
 *   4. the firmware's operations, with its pauses (module code is patched into the running DSP)
 *   5. SRC 202 stream start on our loop (device address 0x1b7d000, win_loop_frames; Windows' 960 by default)
 * Then ALSA device 6 (ct_winplay.c) plays through SRC 202 -> DSP -> Windows' mixer -> DAC.
 * Leaving Windows mode needs a module reload for now (src/rearm.sh).
 *
 * Effects are DATA: a table of controls, each writing words of the running DSP's memory. The addresses belong to the
 * module layout of the load sequence (stable across Windows driver starts).
 */
